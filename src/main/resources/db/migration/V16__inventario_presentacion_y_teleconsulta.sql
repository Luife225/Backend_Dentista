-- Registro y auditoría de importación de catálogo
CREATE TABLE inventario_catalogo_importacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL REFERENCES clinica(id),
    lote_id VARCHAR(80) NOT NULL,
    nombre_archivo VARCHAR(200) NOT NULL,
    hoja VARCHAR(80) NOT NULL,
    total_filas INTEGER NOT NULL,
    filas_importadas INTEGER NOT NULL,
    creado_por_id BIGINT NOT NULL REFERENCES usuario_clinica(id),
    fecha_creacion TIMESTAMPTZ NOT NULL,
    UNIQUE(clinica_id, lote_id)
);
CREATE INDEX idx_catalogo_importacion_clinica ON inventario_catalogo_importacion(clinica_id);

-- Sesión de teleconsulta integrada y alojada localmente
CREATE TABLE teleconsulta_sesion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL REFERENCES clinica(id),
    cita_id BIGINT NOT NULL REFERENCES cita(id),
    sala_id VARCHAR(80) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'PROGRAMADA' CHECK(estado IN ('PROGRAMADA','EN_CURSO','FINALIZADA','CANCELADA')),
    iniciada_por_id BIGINT REFERENCES usuario_clinica(id),
    finalizada_por_id BIGINT REFERENCES usuario_clinica(id),
    fecha_inicio TIMESTAMPTZ,
    fecha_fin TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL,
    UNIQUE(clinica_id, cita_id)
);
CREATE INDEX idx_teleconsulta_cita ON teleconsulta_sesion(cita_id);
CREATE INDEX idx_teleconsulta_sala ON teleconsulta_sesion(sala_id);

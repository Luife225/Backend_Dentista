CREATE TABLE caja_cargo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL REFERENCES clinica(id),
    paciente_id BIGINT NOT NULL REFERENCES paciente(id),
    cita_id BIGINT REFERENCES cita(id),
    creado_por_id BIGINT NOT NULL REFERENCES usuario_clinica(id),
    concepto VARCHAR(200) NOT NULL,
    importe NUMERIC(12,2) NOT NULL CHECK(importe>0),
    estado VARCHAR(16) NOT NULL CHECK(estado IN ('ACTIVO','ANULADO')),
    solicitud_id VARCHAR(80) NOT NULL,
    motivo_anulacion VARCHAR(500), anulado_por_id BIGINT REFERENCES usuario_clinica(id), fecha_anulacion TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL,
    UNIQUE(clinica_id, solicitud_id)
);
CREATE TABLE caja_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL REFERENCES clinica(id),
    cargo_id BIGINT NOT NULL REFERENCES caja_cargo(id),
    creado_por_id BIGINT NOT NULL REFERENCES usuario_clinica(id),
    importe NUMERIC(12,2) NOT NULL CHECK(importe>0),
    medio VARCHAR(20) NOT NULL CHECK(medio IN ('EFECTIVO','TARJETA','TRANSFERENCIA','YAPE','PLIN')),
    referencia VARCHAR(120), solicitud_id VARCHAR(80) NOT NULL,
    anulado BOOLEAN NOT NULL DEFAULT FALSE,
    motivo_anulacion VARCHAR(500), anulado_por_id BIGINT REFERENCES usuario_clinica(id), fecha_anulacion TIMESTAMPTZ,
    fecha_creacion TIMESTAMPTZ NOT NULL,
    UNIQUE(clinica_id, solicitud_id)
);
CREATE TABLE inventario_insumo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL REFERENCES clinica(id),
    nombre VARCHAR(160) NOT NULL, categoria VARCHAR(80) NOT NULL, unidad VARCHAR(40) NOT NULL,
    stock INTEGER NOT NULL DEFAULT 0 CHECK(stock>=0),
    stock_minimo INTEGER NOT NULL CHECK(stock_minimo>=0),
    costo_unitario NUMERIC(12,2) NOT NULL CHECK(costo_unitario>=0), proveedor VARCHAR(160),
    activo BOOLEAN NOT NULL DEFAULT TRUE, fecha_creacion TIMESTAMPTZ NOT NULL
);
CREATE TABLE inventario_movimiento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clinica_id BIGINT NOT NULL REFERENCES clinica(id),
    insumo_id BIGINT NOT NULL REFERENCES inventario_insumo(id),
    creado_por_id BIGINT NOT NULL REFERENCES usuario_clinica(id),
    tipo VARCHAR(16) NOT NULL CHECK(tipo IN ('ENTRADA','SALIDA','AJUSTE')),
    cantidad INTEGER NOT NULL CHECK(cantidad>=0),
    stock_anterior INTEGER NOT NULL CHECK(stock_anterior>=0), stock_resultante INTEGER NOT NULL CHECK(stock_resultante>=0),
    motivo VARCHAR(500) NOT NULL, solicitud_id VARCHAR(80) NOT NULL, fecha_creacion TIMESTAMPTZ NOT NULL,
    UNIQUE(clinica_id, solicitud_id)
);
CREATE INDEX idx_caja_cargo_clinica_fecha ON caja_cargo(clinica_id,fecha_creacion);
CREATE INDEX idx_caja_pago_cargo ON caja_pago(cargo_id);
CREATE INDEX idx_inventario_clinica ON inventario_insumo(clinica_id);
CREATE INDEX idx_inventario_movimientos ON inventario_movimiento(insumo_id,fecha_creacion);

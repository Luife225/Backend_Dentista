-- V24: Convertir mesa_ayuda_ticket.id y mesa_ayuda_bitacora.ticket_id a INT (Entero Autoincremental)
-- y normalizar columnas repetidas respecto a catalogo_incidencia (3FN).

DO $$
DECLARE
    v_col_type TEXT;
    v_max_id INT;
BEGIN
    SELECT data_type INTO v_col_type
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'mesa_ayuda_ticket'
      AND column_name = 'id';

    IF v_col_type IS NOT NULL AND v_col_type <> 'integer' THEN
        -- 1. Eliminar restricción de llave foránea e índice en la tabla hija (mesa_ayuda_bitacora)
        ALTER TABLE mesa_ayuda_bitacora DROP CONSTRAINT IF EXISTS mesa_ayuda_bitacora_ticket_id_fkey;
        DROP INDEX IF EXISTS idx_mesa_bitacora_ticket;

        -- 2. Convertir mesa_ayuda_bitacora.ticket_id a INT extrayendo los dígitos ('TKT-015' -> 15)
        ALTER TABLE mesa_ayuda_bitacora
            ALTER COLUMN ticket_id TYPE INT
            USING COALESCE(NULLIF(REGEXP_REPLACE(ticket_id::TEXT, '[^0-9]', '', 'g'), '')::INT, 1);

        -- 3. Convertir mesa_ayuda_ticket.id a INT extrayendo los dígitos ('TKT-015' -> 15)
        ALTER TABLE mesa_ayuda_ticket
            ALTER COLUMN id TYPE INT
            USING COALESCE(NULLIF(REGEXP_REPLACE(id::TEXT, '[^0-9]', '', 'g'), '')::INT, 1);

        -- 4. Convertir mesa_ayuda_ticket.id en columna autoincremental (IDENTITY) sincronizada al último ticket
        ALTER TABLE mesa_ayuda_ticket
            ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

        SELECT COALESCE(MAX(id), 1) INTO v_max_id FROM mesa_ayuda_ticket;
        PERFORM setval(pg_get_serial_sequence('mesa_ayuda_ticket', 'id'), v_max_id, true);

        -- 5. Restaurar la llave foránea numérica (INT -> INT) y su índice en mesa_ayuda_bitacora
        DELETE FROM mesa_ayuda_bitacora b
        WHERE NOT EXISTS (SELECT 1 FROM mesa_ayuda_ticket t WHERE t.id = b.ticket_id);

        ALTER TABLE mesa_ayuda_bitacora
            ADD CONSTRAINT mesa_ayuda_bitacora_ticket_id_fkey
            FOREIGN KEY (ticket_id) REFERENCES mesa_ayuda_ticket(id) ON DELETE CASCADE;

        CREATE INDEX idx_mesa_bitacora_ticket ON mesa_ayuda_bitacora(ticket_id, fecha_hora ASC);
    END IF;

    -- 6. Normalización (3FN): Eliminar de mesa_ayuda_ticket los atributos que ya pertenecen a catalogo_incidencia
    ALTER TABLE mesa_ayuda_ticket DROP COLUMN IF EXISTS tipo_itil;
    ALTER TABLE mesa_ayuda_ticket DROP COLUMN IF EXISTS sla_minutos;
    ALTER TABLE mesa_ayuda_ticket DROP COLUMN IF EXISTS ruta_accion;
    ALTER TABLE mesa_ayuda_ticket DROP COLUMN IF EXISTS accion_label;
END $$;
